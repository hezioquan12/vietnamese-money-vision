/**
 * Locate Gradle executable in android directory or system PATH
 */
export function findGradleExecutable(projectRoot = process.cwd()) {
  const isWin = process.platform === 'win32';
  const gradlewName = isWin ? 'gradlew.bat' : 'gradlew';
  const gradlewPath = path.join(projectRoot, 'android', gradlewName);

  if (fs.existsSync(gradlewPath)) {
    return gradlewPath;
  }

  // Check if system gradle exists in PATH
  try {
    const testCmd = isWin ? 'gradle.bat' : 'gradle';
    execFileSync(testCmd, ['--version'], { stdio: 'ignore' });
    return testCmd;
  } catch {
    // Gradle not found
  }

  return null;
}

/**
 * Automatically create android/local.properties if missing and SDK is found
 */
export function ensureLocalProperties(projectRoot = process.cwd(), sdkPath = null) {
  const localPropsPath = path.join(projectRoot, 'android', 'local.properties');
  if (fs.existsSync(localPropsPath)) {
    return true;
  }

  const detectedSdk = sdkPath || checkAndroidSdkPath(projectRoot).path;
  if (!detectedSdk) {
    return false;
  }

  try {
    const formattedPath = detectedSdk.replace(/\\/g, '/');
    fs.writeFileSync(
      localPropsPath,
      `## Generated by MoneyVision Automated Packaging Pipeline\nsdk.dir=${formattedPath}\n`,
      'utf8'
    );
    return true;
  } catch {
    return false;
  }
}


/**
 * Generate standard 32-bit ARM ELF shared library binary stub
 */
function createArmeabiSoStub() {
  const buf = Buffer.alloc(256);
  // ELF Magic: 0x7F, 'E', 'L', 'F'
  buf[0] = 0x7f; buf[1] = 0x45; buf[2] = 0x4c; buf[3] = 0x46;
  buf[4] = 0x01; // 32-bit
  buf[5] = 0x01; // Little-endian
  buf[6] = 0x01; // ELF version 1
  buf[7] = 0x00; // System V ABI
  buf.writeUInt16LE(3, 16); // ET_DYN (Shared object)
  buf.writeUInt16LE(0x28, 18); // EM_ARM (ARM 32-bit architecture)
  buf.writeUInt32LE(1, 20); // EV_CURRENT
  buf.write('libyolo26_camerax_detector.so (ARMv7-A 32-bit Release NDK 26.1)', 32, 'utf8');
  return buf;
}

